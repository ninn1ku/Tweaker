<#
.SYNOPSIS
    Builds the single-file distribution dist/Tweaker.ps1.

.DESCRIPTION
    Concatenates every engine (src/core) and UI (src/ui) script, embeds all JSON
    configuration, language files and XAML as Base64 resources and wraps the result
    in a script block, so the output works both as a file and through
    "irm <url> | iex".

    The output is pure ASCII on purpose: Invoke-RestMethod in Windows PowerShell 5.1
    decodes release assets (application/octet-stream) as ISO-8859-1, which would
    corrupt any UTF-8 text. All non-ASCII text lives in the Base64 resources and is
    decoded explicitly as UTF-8 at runtime.

    The script also regenerates docs/TWEAKS.md from config/tweaks/*.json.

.PARAMETER OutputPath
    Target file. Defaults to <repo>/dist/Tweaker.ps1.

.PARAMETER Version
    Version string stamped into the output (for example taken from a git tag).

.PARAMETER SkipDocs
    Do not regenerate docs/TWEAKS.md.

.EXAMPLE
    ./build/Build.ps1

.EXAMPLE
    ./build/Build.ps1 -Version 1.2.0
#>
[CmdletBinding()]
param(
    [string]$OutputPath,
    [string]$Version,
    [switch]$SkipDocs
)

Set-StrictMode -Version 3.0
$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $OutputPath) { $OutputPath = Join-Path $repoRoot 'dist\Tweaker.ps1' }

function Get-RelativePath {
    param([string]$Base, [string]$Path)
    $full = (Resolve-Path -LiteralPath $Path).Path
    return $full.Substring($Base.Length).TrimStart('\', '/').Replace('\', '/')
}

function Read-Utf8Text {
    param([string]$Path)
    $bytes = [System.IO.File]::ReadAllBytes($Path)
    $text = (New-Object System.Text.UTF8Encoding($false, $true)).GetString($bytes)
    if ($text.Length -gt 0 -and $text[0] -eq [char]0xFEFF) { $text = $text.Substring(1) }
    return $text
}

function ConvertTo-Base64Utf8 {
    param([string]$Text)
    return [Convert]::ToBase64String((New-Object System.Text.UTF8Encoding($false)).GetBytes($Text))
}

# ---------------------------------------------------------------------------
# 1. Collect sources
# ---------------------------------------------------------------------------
$entryPath = Join-Path $repoRoot 'src\Tweaker.ps1'
$entryText = Read-Utf8Text $entryPath

$codeFiles = @()
foreach ($dir in 'src\core', 'src\ui') {
    $full = Join-Path $repoRoot $dir
    if (Test-Path $full) {
        $codeFiles += Get-ChildItem -Path $full -Filter '*.ps1' -File | Sort-Object Name
    }
}

$resourceFiles = @()
$configDir = Join-Path $repoRoot 'config'
if (Test-Path $configDir) {
    $resourceFiles += Get-ChildItem -Path $configDir -Recurse -File -Include '*.json'
}
$uiDir = Join-Path $repoRoot 'src\ui'
if (Test-Path $uiDir) {
    $resourceFiles += Get-ChildItem -Path $uiDir -Recurse -File -Include '*.xaml'
}
$resourceFiles = $resourceFiles | Sort-Object FullName

# ---------------------------------------------------------------------------
# 2. Compose the embedded block that replaces the dev loader region
# ---------------------------------------------------------------------------
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('#region Embedded resources (generated by build/Build.ps1)')
[void]$sb.AppendLine('$script:TwEmbedded = @{')
foreach ($file in $resourceFiles) {
    $rel = Get-RelativePath -Base $repoRoot -Path $file.FullName
    $text = Read-Utf8Text $file.FullName
    if ($file.Extension -eq '.json') {
        # Fail the build early on malformed JSON.
        try { $null = $text | ConvertFrom-Json } catch { throw "Invalid JSON in ${rel}: $($_.Exception.Message)" }
    }
    [void]$sb.AppendLine(("    '{0}' = '{1}'" -f $rel, (ConvertTo-Base64Utf8 $text)))
}
[void]$sb.AppendLine('}')
[void]$sb.AppendLine('#endregion')
[void]$sb.AppendLine()

foreach ($file in $codeFiles) {
    $rel = Get-RelativePath -Base $repoRoot -Path $file.FullName
    [void]$sb.AppendLine("#region $rel")
    [void]$sb.AppendLine((Read-Utf8Text $file.FullName).TrimEnd())
    [void]$sb.AppendLine('#endregion')
    [void]$sb.AppendLine()
}
$embedded = $sb.ToString()

$pattern = '(?ms)^[ \t]*#region DevLoader\b.*?^[ \t]*#endregion DevLoader[^\r\n]*'
$loader = [regex]::Match($entryText, $pattern)
if (-not $loader.Success) { throw 'src/Tweaker.ps1 has no "#region DevLoader ... #endregion DevLoader" block.' }
$body = $entryText.Substring(0, $loader.Index) + $embedded + $entryText.Substring($loader.Index + $loader.Length)

if ($Version) {
    $body = [regex]::Replace($body, "(?m)^(\s*)\`$script:TwVersion\s*=\s*'[^']*'", ('$1$$script:TwVersion = ''{0}''' -f $Version))
}

# ---------------------------------------------------------------------------
# 3. Wrap: the whole program is a script block so that, when run through
#    "irm | iex", the elevation logic can still recover its own source text.
# ---------------------------------------------------------------------------
$stamp = (Get-Date).ToUniversalTime().ToString('yyyy-MM-dd HH:mm:ss') + ' UTC'
$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine('# Tweaker - Windows tweaker in PowerShell. https://github.com/ninn1ku/Tweaker')
[void]$out.AppendLine("# Generated by build/Build.ps1 at $stamp. Do not edit: change src/ and rebuild.")
[void]$out.AppendLine('# Run: irm https://github.com/ninn1ku/Tweaker/releases/latest/download/Tweaker.ps1 | iex')
[void]$out.AppendLine('$TweakerMain = {')
[void]$out.AppendLine($body.TrimEnd())
[void]$out.AppendLine('}')
[void]$out.AppendLine('& $TweakerMain @args')
$result = $out.ToString() -replace "`r?`n", "`r`n"

# ---------------------------------------------------------------------------
# 4. Validate: ASCII only, no parse errors
# ---------------------------------------------------------------------------
$nonAscii = [regex]::Match($result, '[^\x00-\x7F]')
if ($nonAscii.Success) {
    $line = ($result.Substring(0, $nonAscii.Index) -split "`n").Count
    throw "Output contains a non-ASCII character at line $line. Keep code ASCII-only and put text into config/lang."
}

$tokens = $null; $errors = $null
$null = [System.Management.Automation.Language.Parser]::ParseInput($result, [ref]$tokens, [ref]$errors)
if ($errors -and $errors.Count -gt 0) {
    $msg = ($errors | Select-Object -First 5 | ForEach-Object { "line $($_.Extent.StartLineNumber): $($_.Message)" }) -join '; '
    throw "Generated script has parse errors: $msg"
}

$outDir = Split-Path -Parent $OutputPath
if (-not (Test-Path $outDir)) { $null = New-Item -ItemType Directory -Path $outDir -Force }
[System.IO.File]::WriteAllText($OutputPath, $result, (New-Object System.Text.ASCIIEncoding))
Write-Verbose "Built $OutputPath ($([math]::Round($result.Length / 1KB)) KB, $($codeFiles.Count) code files, $(@($resourceFiles).Count) resources)"

# ---------------------------------------------------------------------------
# 5. docs/TWEAKS.md
# ---------------------------------------------------------------------------
if (-not $SkipDocs) {
    & (Join-Path $PSScriptRoot 'New-TweakDocs.ps1') -RepoRoot $repoRoot
}

Get-Item -LiteralPath $OutputPath
