<#
.SYNOPSIS
    Generates docs/TWEAKS.md from config/tweaks/*.json.

.DESCRIPTION
    The document is produced in Russian (the default UI language). All headings come
    from config/lang/ru.json ("docs.*" keys) so this script stays ASCII-only.

.PARAMETER RepoRoot
    Repository root. Defaults to the parent of this script's folder.

.PARAMETER Language
    Language for names, descriptions and headings: ru (default) or en.
#>
[CmdletBinding()]
param(
    [string]$RepoRoot = (Split-Path -Parent $PSScriptRoot),
    [ValidateSet('ru', 'en')]
    [string]$Language = 'ru'
)

Set-StrictMode -Version 3.0
$ErrorActionPreference = 'Stop'

function Read-JsonFile {
    param([string]$Path)
    $text = [System.IO.File]::ReadAllText($Path, [System.Text.Encoding]::UTF8)
    return $text | ConvertFrom-Json
}

function Get-Prop {
    param($Object, [string]$Name, $Default = $null)
    if ($null -ne $Object -and $Object.PSObject.Properties[$Name]) { return $Object.$Name }
    return $Default
}

$langFile = Join-Path $RepoRoot "config\lang\$Language.json"
$strings = if (Test-Path $langFile) { Read-JsonFile $langFile } else { $null }
function T {
    param([string]$Key, [string]$Fallback)
    $value = Get-Prop $strings $Key
    if ($value) { return $value }
    return $Fallback
}

$categoriesFile = Join-Path $RepoRoot 'config\categories.json'
$categories = if (Test-Path $categoriesFile) { @((Read-JsonFile $categoriesFile).categories) } else { @() }

$tweaks = @()
$tweakDir = Join-Path $RepoRoot 'config\tweaks'
if (Test-Path $tweakDir) {
    foreach ($file in Get-ChildItem $tweakDir -Filter '*.json' | Sort-Object Name) {
        $tweaks += @((Read-JsonFile $file.FullName).tweaks)
    }
}

$nl = "`n"
$md = New-Object System.Text.StringBuilder
[void]$md.Append('# ' + (T 'docs.title' 'Tweaks') + $nl + $nl)
[void]$md.Append('> ' + (T 'docs.generated' 'Generated by build/New-TweakDocs.ps1 from config/tweaks/*.json. Do not edit by hand.') + $nl + $nl)
[void]$md.Append((T 'docs.total' 'Total tweaks') + ': **' + $tweaks.Count + '**' + $nl + $nl)
[void]$md.Append((T 'docs.legend' 'Legend') + $nl + $nl)

$orderedCategories = @($categories | Where-Object { $_.page -eq 'tweaks' } | Sort-Object order)
foreach ($cat in $orderedCategories) {
    $catTweaks = @($tweaks | Where-Object { $_.category -eq $cat.id })
    if ($catTweaks.Count -eq 0) { continue }
    [void]$md.Append('## ' + (T "category.$($cat.id)" $cat.id) + ' (' + $catTweaks.Count + ')' + $nl + $nl)
    [void]$md.Append('| ' + ((T 'docs.col.tweak' 'Tweak'), (T 'docs.col.risk' 'Risk'), (T 'docs.col.builds' 'Builds'), (T 'docs.col.flags' 'Flags'), (T 'docs.col.presets' 'Presets'), (T 'docs.col.source' 'Source') -join ' | ') + ' |' + $nl)
    [void]$md.Append('|---|---|---|---|---|---|' + $nl)
    foreach ($t in $catTweaks) {
        $name = (Get-Prop $t.name $Language $t.id) -replace '\|', '\|'
        $desc = (Get-Prop $t.description $Language '') -replace '\|', '\|' -replace '\r?\n', ' '
        $min = Get-Prop $t 'minBuild'
        $max = Get-Prop $t 'maxBuild'
        $builds = if ($min -and $max) { "$min-$max" } elseif ($min) { "$min+" } elseif ($max) { "<= $max" } else { (T 'docs.anyBuild' 'any') }
        $flags = @()
        if (Get-Prop $t 'requiresReboot' $false) { $flags += (T 'docs.flag.reboot' 'reboot') }
        if (Get-Prop $t 'requiresSignOut' $false) { $flags += (T 'docs.flag.signout' 'sign-out') }
        if (Get-Prop $t 'requiresExplorerRestart' $false) { $flags += (T 'docs.flag.explorer' 'Explorer') }
        if (-not (Get-Prop $t 'verified' $false)) { $flags += (T 'docs.flag.unverified' 'unverified') }
        $presets = @(Get-Prop $t 'presets' @()) -join ', '
        $source = Get-Prop $t 'source' ''
        $sourceCell = if ($source) { "[link]($source)" } else { '-' }
        $risk = T "risk.$($t.risk)" $t.risk
        $cell = "**$name**<br>``$($t.id)``<br>$desc"
        [void]$md.Append("| $cell | $risk | $builds | $(($flags -join ', ')) | $presets | $sourceCell |" + $nl)
    }
    [void]$md.Append($nl)
}

$outFile = Join-Path $RepoRoot 'docs\TWEAKS.md'
$outDir = Split-Path -Parent $outFile
if (-not (Test-Path $outDir)) { $null = New-Item -ItemType Directory -Path $outDir -Force }
[System.IO.File]::WriteAllText($outFile, $md.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Verbose "Generated $outFile ($($tweaks.Count) tweaks)"
